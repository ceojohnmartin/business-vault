#!/bin/sh
# Regenerate the paste-ready transaction file from the migration, so the two
# can never drift:
#   db/APPLY_rally100_v1.sql  <-  db/migrations/1001_rally100_v1.sql
#
#   sh rally-100/db/build-apply.sh           rewrite APPLY_rally100_v1.sql
#   sh rally-100/db/build-apply.sh --check   exit 1 if it is out of date
#
# The header is written here, not kept from the old file, so the APPLY file
# is a pure function of the migration and this script.
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"
MIG="$DIR/migrations/1001_rally100_v1.sql"
OUT="$DIR/APPLY_rally100_v1.sql"

build() {
  cat <<'HEADER'
-- RALLY 100 v1 — APPLY. Paste this whole file into the Supabase SQL editor
-- (as postgres) and run it once. GENERATED by rally-100/db/build-apply.sh
-- from db/migrations/1001_rally100_v1.sql; edit the migration, never this.
--
-- ALL OR NOTHING. It is one transaction: if any statement fails, nothing is
-- left behind and RALLY is exactly as it was. It creates schema rally100 and
-- touches nothing in RALLY's public schema. It is not re-runnable: a second
-- run stops at `create schema rally100` and changes nothing.
--
-- AFTER IT COMMITS:
--   1. Project Settings -> Data API -> Exposed schemas: add rally100.
--   2. Check: `select count(*) from pg_proc p join pg_namespace n
--      on n.oid = p.pronamespace where n.nspname = 'rally100'
--      and has_function_privilege('authenticated', p.oid, 'execute');`
--      must answer 39.
-- TO UNDO: rally-100/db/ROLLBACK_rally100_v1.sql (removes RALLY 100 only).

begin;

HEADER
  cat "$MIG"
  printf '\ncommit;\n'
}

if [ "${1:-}" = "--check" ]; then
  TMP="$(mktemp)"
  build > "$TMP"
  if cmp -s "$TMP" "$OUT"; then
    rm -f "$TMP"; echo "APPLY: in sync with the migration"
  else
    rm -f "$TMP"; echo "APPLY: OUT OF DATE — run sh rally-100/db/build-apply.sh"; exit 1
  fi
else
  build > "$OUT.tmp"
  mv "$OUT.tmp" "$OUT"
  echo "regenerated $OUT"
fi
