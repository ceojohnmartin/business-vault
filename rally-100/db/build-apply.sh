#!/bin/sh
# Regenerate the paste-ready transaction files from the migrations, so the
# two can never drift:
#   db/APPLY_rally100_v1.sql  <-  db/migrations/1001_rally100_v1.sql
#   db/APPLY_rally100_v2.sql  <-  db/migrations/1002_rally100_auto_join.sql
#
#   sh rally-100/db/build-apply.sh           rewrite both APPLY files
#   sh rally-100/db/build-apply.sh --check   exit 1 if either is out of date
#
# The headers are written here, not kept from the old files, so each APPLY
# file is a pure function of its migration and this script. v1's header and
# output are frozen: production ran APPLY_rally100_v1.sql exactly as built.
set -e
DIR="$(cd "$(dirname "$0")" && pwd)"

header_v1() {
  cat <<'HEADER'
-- RALLY 100 v1 — APPLY. Paste this whole file into the Supabase SQL editor
-- (as postgres) and run it once. GENERATED by rally-100/db/build-apply.sh
-- from db/migrations/1001_rally100_v1.sql; edit the migration, never this.
--
-- ALL OR NOTHING. It is one transaction: if any statement fails, nothing is
-- left behind and RALLY is exactly as it was. It creates schema rally100 and
-- touches nothing in RALLY's public schema. It is not re-runnable: a second
-- run stops at `create schema rally100` and changes nothing.
--
-- AFTER IT COMMITS:
--   1. Project Settings -> Data API -> Exposed schemas: add rally100.
--   2. Check: `select count(*) from pg_proc p join pg_namespace n
--      on n.oid = p.pronamespace where n.nspname = 'rally100'
--      and has_function_privilege('authenticated', p.oid, 'execute');`
--      must answer 40.
-- TO UNDO: rally-100/db/ROLLBACK_rally100_v1.sql (removes RALLY 100 only).

begin;

HEADER
}

header_v2() {
  cat <<'HEADER'
-- RALLY 100 v2 — APPLY: automatic team joining for new sign-ups. Paste this
-- whole file into the Supabase SQL editor (as postgres) and run it once,
-- AFTER v1 (APPLY_rally100_v1.sql). GENERATED by rally-100/db/build-apply.sh
-- from db/migrations/1002_rally100_auto_join.sql; edit the migration, never
-- this.
--
-- ALL OR NOTHING. It is one transaction: if any statement fails, nothing is
-- left behind. It creates and alters objects inside schema rally100 only.
-- Without v1 it stops at its first statement; it is not re-runnable either:
-- a second run stops at `create table rally100.settings`. Both change nothing.
--
-- WHAT IT SWITCHES ON. With exactly one team that has an owner on it, new
-- sign-ups who confirm their email join that team as reps from the moment
-- this commits, and joining the team lets them see RALLY team data. With no
-- such team, or two or more, the switch starts off. The Owner Dashboard
-- shows the switch and turns it off or on at any time.
--
-- AFTER IT COMMITS:
--   1. Check: the same count as v1's check must now answer 42.
--   2. `select auto_join_team from rally100.settings;` is your team's id
--      (on) or null (off).
--   3. `select count(*) from auth.users where email_confirmed_at is not null;`
--      answers without an error and is not 0 (v2 reads that column to
--      decide who counts as confirmed).
-- TO UNDO: rally-100/db/ROLLBACK_rally100_v2.sql (removes automatic joining
-- only; people it already placed stay on the team).

begin;

HEADER
}

build() {  # $1 = header function, $2 = migration
  "$1"
  cat "$2"
  printf '\ncommit;\n'
}

STATUS=0
for v in v1 v2; do
  case "$v" in
    v1) MIG="$DIR/migrations/1001_rally100_v1.sql" ;;
    v2) MIG="$DIR/migrations/1002_rally100_auto_join.sql" ;;
  esac
  OUT="$DIR/APPLY_rally100_$v.sql"
  if [ "${1:-}" = "--check" ]; then
    TMP="$(mktemp)"
    build "header_$v" "$MIG" > "$TMP"
    if cmp -s "$TMP" "$OUT"; then
      echo "APPLY $v: in sync with $(basename "$MIG")"
    else
      echo "APPLY $v: OUT OF DATE — run sh rally-100/db/build-apply.sh"; STATUS=1
    fi
    rm -f "$TMP"
  else
    build "header_$v" "$MIG" > "$OUT.tmp"
    mv "$OUT.tmp" "$OUT"
    echo "regenerated $OUT"
  fi
done
exit $STATUS
